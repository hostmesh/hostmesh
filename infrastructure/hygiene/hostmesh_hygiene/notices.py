"""THIRD_PARTY_NOTICES: the license files of what Hostmesh contains or ships.

The text must be the same wherever it is generated, and must not change
with a patch release: no versions, no absolute paths, normalised line
endings, a fixed order.
"""

from collections.abc import Iterable
from pathlib import Path

from hostmesh_hygiene.inventory import Package
from hostmesh_hygiene.policy import Vendored

_RULE = "=" * 78
_THIN_RULE = "-" * 78
_LICENSE_FILE_PREFIXES = ("LICENSE", "LICENCE", "COPYING", "NOTICE")

_SECTIONS = {
    "composer": ("Composer packages (control plane)", "https://packagist.org/packages/{name}"),
    "npm": ("npm packages (admin app and customer portal)", "https://www.npmjs.com/package/{name}"),
    "python": ("Python packages (node agent)", "https://pypi.org/project/{name}/"),
}

_HEADER = """\
THIRD-PARTY NOTICES

Hostmesh is licensed under the Apache License, Version 2.0 (see LICENSE and
NOTICE). This file reproduces the license and notice files of the
third-party software that Hostmesh contains or ships: source code that lives
in this repository, and the production dependencies that a build or an
installation includes. Development-only dependencies are not listed; the
license scan covers them (infrastructure/hygiene/README.md).

Generated by `make -C infrastructure/hygiene notices`. Do not edit: CI fails
when this file differs from what the command writes.
"""


def render(packages: Iterable[Package], vendored: Iterable[Vendored], repo_root: Path) -> str:
    parts = [_HEADER]

    sources = list(vendored)
    if sources:
        parts.append(_title("Source code in this repository"))
        parts.extend(_vendored(source, repo_root) for source in sources)

    listed = list(packages)
    for ecosystem, (title, url) in _SECTIONS.items():
        chosen = {
            package.name.lower(): package for package in listed if package.ecosystem == ecosystem
        }
        if not chosen:
            continue
        parts.append(_title(title))
        parts.extend(_package(chosen[name], url) for name in sorted(chosen))

    return "\n".join(parts).rstrip("\n") + "\n"


def _title(text: str) -> str:
    return f"{_RULE}\n{text}\n{_RULE}\n"


def _vendored(source: Vendored, repo_root: Path) -> str:
    lines = [source.name, f"License: {source.license}", source.source, "Files:"]
    lines += [f"  {path}" for path in source.paths]
    lines.append("")
    if source.license_file is None:
        lines.append(_no_license_file())
    else:
        lines.append(_clean((repo_root / source.license_file).read_bytes()))
    return "\n".join(lines) + f"\n\n{_THIN_RULE}\n"


def _package(package: Package, url: str) -> str:
    lines = [package.name, f"License: {package.license}", url.format(name=package.name), ""]
    texts = _license_texts(package.path)
    lines.append("\n\n".join(texts) if texts else _no_license_file())
    return "\n".join(lines) + f"\n\n{_THIN_RULE}\n"


def _no_license_file() -> str:
    return "This software ships no license file; it declares the license named above."


def _license_texts(directory: Path | None) -> list[str]:
    """License and notice files: in the package directory, and in a dist-info `licenses/`."""
    if directory is None or not directory.is_dir():
        return []
    candidates = [path for path in directory.iterdir() if path.is_file()]
    licenses = directory / "licenses"
    if licenses.is_dir():
        candidates += [path for path in licenses.rglob("*") if path.is_file()]
    chosen = sorted(
        (path for path in candidates if path.name.upper().startswith(_LICENSE_FILE_PREFIXES)),
        key=lambda path: path.relative_to(directory).as_posix().lower(),
    )
    return [
        f"[{path.relative_to(directory).as_posix()}]\n{_clean(path.read_bytes())}"
        for path in chosen
    ]


def _clean(raw: bytes) -> str:
    text = raw.decode("utf-8", errors="replace").removeprefix("﻿")
    lines = [line.rstrip() for line in text.replace("\r\n", "\n").replace("\r", "\n").split("\n")]
    return "\n".join(lines).strip("\n")
